import { SkillType } from '../services/skill-detector.service';

/**
 * Language alternative for a direction (genuinely equivalent, not a downgrade)
 */
export interface LanguageAlternative {
  language: string; // "Python"
  reason: string; // "Good for data-focused projects"
  tradeoffs?: string; // "Slightly slower feedback loop"
}

/**
 * Language configuration for code-based directions
 * AI generates this based on project requirements
 */
export interface LanguageConfig {
  recommended: string; // "TypeScript"
  recommendedReason: string; // "Best tooling + sandbox support"
  alternatives?: LanguageAlternative[];
  // Languages that would fundamentally change the project (don't offer these)
  notRecommended?: {
    language: string;
    reason: string; // "Would require different architecture"
  }[];
}

/**
 * Direction generated by AI during onboarding.
 * Each direction is:
 * - SEARCHABLE: Uses common terms that YouTube videos would use
 * - BOUNDED: Achievable in 30-90 minutes of learning
 * - ACTIONABLE: Can become a concrete curriculum topic
 */
export interface LearningDirection {
  id: string;
  title: string; // "Webhooks + APIs for automations" (max 8 words)
  outcome: string; // "You'll be able to build reliable integrations"
  keywords: string[]; // ["webhooks", "API", "requests", "auth"] - for video search
  isToolSpecific: boolean; // true for Zapier/Make specific, false for concept
  estimatedMinutes: number; // 30, 45, 60, or 90
  paymentNote?: string; // e.g., "May require paid subscription" for non-free tools
  isFree?: boolean; // true for free tools like Python, false for paid tools like Zapier
  skillType?: SkillType; // Detected skill type for this direction (CODE, KNOWLEDGE, PHYSICAL, etc.)
  // Language config for CODE/AI_AGENT directions (AI decides if applicable)
  languageConfig?: LanguageConfig;
}

/**
 * Output types - what the user wants to achieve from learning.
 * Universal across all skill types (code, knowledge, physical).
 *
 * - apply_skill: Use the skill proficiently. Practical application, make it work.
 * - ship_project: Ship something real. End-to-end, deployment, best practices.
 * - understand_concept: Deep understanding. Theory, mental models, "why" explanations.
 * - pass_exam: Pass an exam. Memorizable facts, practice questions, exam strategies.
 * - teach_others: Teach others. Analogies, clear explanations, common misconceptions.
 * - compete: Compete with others. Advanced techniques, competitive strategies.
 * - master_basics: Master fundamentals. Core techniques, solid foundation.
 */
export type OutputType =
  | 'apply_skill'
  | 'ship_project'
  | 'understand_concept'
  | 'pass_exam'
  | 'teach_others'
  | 'compete'
  | 'master_basics';

/**
 * Refinement context from Step 3b of onboarding.
 * Used when user clicks "Not quite" to help AI generate better directions.
 */
export interface RefinementContext {
  outputType?: OutputType;
  usageContext?: 'work' | 'personal' | 'interview' | 'school';
  platformTolerance?: 'any' | 'preferGeneric' | 'genericOnly';
  userFeedback?: string; // Free-text: "I want X instead of Y" or "Focus more on Z"
  previousDirections?: string; // JSON string of previously generated directions (to avoid regenerating)
}

/**
 * Full learner preferences stored in User.preferences.learner.
 * Captures user's learning intent and preferences for personalized content.
 */
export interface LearnerPrefs {
  // From onboarding Step 1: Free-text goal (kept for reference, not passed to curriculum)
  originalGoal: string; // User's raw input: "I want to learn AI automations"

  // From onboarding Step 4: Selected direction
  selectedDirection: string; // The direction title they picked
  selectedDirectionOutcome: string; // "You'll be able to..." - specific deliverable
  directionKeywords: string[]; // Keywords for video matching hints

  // From onboarding Step 4b: Language selection (for CODE/AI_AGENT directions)
  selectedLanguage?: string; // User's chosen language (or recommended default)

  // From refinement (Step 3b, if used)
  outputType?: OutputType; // What user wants to achieve (affects content style)
  usageContext?: 'work' | 'personal' | 'interview' | 'school';

  // From feeling step (Step 5) - easier for users than explicit skill/time questions
  contentDepth: 'fast' | 'medium' | 'deep'; // Derived from goal type selection
  familiarity?: 'new' | 'know_basics' | 'skilled'; // How familiar with the topic
  sessionLength?: 'short' | 'medium' | 'long'; // Daily learning time availability

  // Learning style preference - explicitly choose projects vs practice
  // 'projects' = build a real project across days (boss project)
  // 'practice' = daily quizzes, exercises, challenges (no boss project)
  learningStyle?: 'projects' | 'practice';

  // Advanced mode: enables code writing exercises (codeCompletion) in intensive practice
  // Default: false (AI code review only - identify issues in AI-generated code)
  // When true: also includes codeCompletion exercises (write code from scratch)
  codeWritingEnabled?: boolean;

  // Platform tolerance (from direction label or refinement)
  // KEY for solving the "Zapier problem" - affects TOOL_SPECIFIC video penalty
  platformTolerance?: 'any' | 'preferGeneric' | 'genericOnly';

  // Metadata
  completedOnboarding: boolean;
  onboardingCompletedAt?: string; // ISO date string
  version: number; // For future migrations
}

/**
 * Default values for new users who haven't completed onboarding.
 */
export const DEFAULT_LEARNER_PREFS: Partial<LearnerPrefs> = {
  platformTolerance: 'preferGeneric',
  contentDepth: 'medium',
  completedOnboarding: false,
  version: 1,
};

// ============================================
// API DTOs
// ============================================

/**
 * Request body for POST /onboarding/generate-directions
 */
export interface GenerateDirectionsDto {
  goal: string; // User's free-text goal
  refinement?: RefinementContext; // Optional refinement context
}

/**
 * Response from POST /onboarding/generate-directions
 */
export interface DirectionsResponse {
  directions: LearningDirection[];
  interpretedGoal: string; // AI's understanding for transparency
}

/**
 * Request body for POST /onboarding/complete
 */
export interface CompleteOnboardingDto {
  originalGoal: string;
  selectedDirection: string;
  selectedDirectionOutcome: string; // "You'll be able to..." from the direction
  directionKeywords: string[];
  contentDepth: 'fast' | 'medium' | 'deep';
  platformTolerance?: 'any' | 'preferGeneric' | 'genericOnly';

  // Language selection (for CODE/AI_AGENT directions)
  selectedLanguage?: string; // User's chosen language (or recommended default)

  // Optional refinement data
  outputType?: OutputType; // What user wants to achieve (working_code, pass_exam, teach_others, etc.)
  usageContext?: 'work' | 'personal' | 'interview' | 'school';

  // Feeling-based inputs (easier than explicit skill level/time questions)
  familiarity?: 'new' | 'know_basics' | 'skilled';
  sessionLength?: 'short' | 'medium' | 'long';

  // Learning style preference - explicitly choose projects vs practice
  learningStyle?: 'projects' | 'practice';

  // Advanced mode: enables code writing exercises in intensive practice
  codeWritingEnabled?: boolean;

  // Analytics: time spent in onboarding flow (tracked client-side)
  durationSeconds?: number;
}

